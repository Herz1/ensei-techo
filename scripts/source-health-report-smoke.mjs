import assert from "node:assert/strict";
import { buildReportedSourceHealth } from "./source-health-report.mjs";
const source = { id: "zero", name: "来源", status: "ok", recordCount: 0 };
const report = { batchId: "batch-1", generatedAt: "2026-09-15T00:00:00Z", collectionWindow: { from: "2026-09-15", months: ["2026-09"] }, sources: [source] };
const manifest = { batchId: "batch-1", entries: [{ sourceId: "zero", requestedUrl: "https://example.test/", fetchStatus: "success", parserStatus: "success" }] };
const first = buildReportedSourceHealth(report, manifest);
const repeated = buildReportedSourceHealth(report, manifest, first.snapshot);
assert.deepEqual(repeated.snapshot, first.snapshot, "重复生成同批健康快照必须幂等");
assert.equal(first.snapshot.sources[0].health.consecutiveAnomalies, 1);
const next = buildReportedSourceHealth({ ...report, batchId: "batch-2" }, { ...manifest, batchId: "batch-2" }, first.snapshot);
assert.equal(next.snapshot.sources[0].health.consecutiveAnomalies, 2);
const mismatch = buildReportedSourceHealth(report, { ...manifest, batchId: "other" });
assert.equal(mismatch.snapshot.sources[0].health.state, "evidence_missing");
assert.equal(mismatch.warnings.length, 1);
const historical = buildReportedSourceHealth({ generatedAt: "2026-07-30T00:00:00Z", sources: [{ ...source, id: "kuroko-kun-hall-official" }] }, { generatedAt: "2026-07-30T00:00:00Z", entries: [{ ...manifest.entries[0], sourceId: "kuroko-kun-hall-official" }] });
assert.deepEqual(historical.snapshot.collectionWindow, { from: null, months: [] });
assert.equal(historical.snapshot.sources[0].health.state, "unexpected_zero");
const noEvidence = buildReportedSourceHealth({ ...report, sources: [{ ...source, recordCount: 5 }] }, { ...manifest, entries: [] });
assert.equal(noEvidence.snapshot.sources[0].health.state, "evidence_missing");
assert.throws(() => buildReportedSourceHealth({ ...report, collectionWindow: { months: ["2026-13"] } }, manifest));
console.log("Source Health report: batch binding, unknown window, missing evidence and idempotence passed");
